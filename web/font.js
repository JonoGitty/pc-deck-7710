// Draw a 5x7 string into framebuffer fb (Uint8Array GRID_W*GRID_H).
// scale multiplies each dot; intensity 1..3. Returns pixel width drawn.
function drawText5(fb, x, y, str, intensity, scale) {
  scale = scale || 1;
  intensity = intensity || 2;
  let cx = x;
  for (const ch of str.toUpperCase()) {
    const g = FONT5[ch] || FONT5["?"];
    for (let row = 0; row < 7; row++) {
      const bits = g[row];
      for (let col = 0; col < 5; col++) {
        if (bits & (0x10 >> col)) {
          for (let sy = 0; sy < scale; sy++)
            for (let sx = 0; sx < scale; sx++)
              setDot(fb, cx + col * scale + sx, y + row * scale + sy, intensity);
        }
      }
    }
    cx += (5 + 1) * scale;
  }
  return cx - x;
}

function drawText3(fb, x, y, str, intensity) {
  intensity = intensity || 2;
  let cx = x;
  for (const ch of str.toUpperCase()) {
    const g = FONT3[ch] || FONT3[" "];
    for (let row = 0; row < 5; row++) {
      const bits = g[row];
      for (let col = 0; col < 3; col++) {
        if (bits & (4 >> col)) setDot(fb, cx + col, y + row, intensity);
      }
    }
    cx += 4;
  }
  return cx - x;
}

function textWidth5(str, scale) { return str.length * 6 * (scale || 1); }
function textWidth3(str) { return str.length * 4; }
